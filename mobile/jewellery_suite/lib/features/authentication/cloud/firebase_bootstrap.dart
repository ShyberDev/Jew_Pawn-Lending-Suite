import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import '../../../firebase_options.dart';

/// Starts Firebase once and remembers whether it is usable.
///
/// The app is offline-first: a phone without `android/app/google-services.json`
/// (or without network at first launch) must still open the shop. So the only
/// failure mode here is a `false` return plus a debug line — never a throw.
class FirebaseBootstrap {
  const FirebaseBootstrap._();

  static bool _ready = false;
  static String? _error;

  /// True when [Firebase.initializeApp] succeeded, so `FirebaseAuth` and
  /// `FirebaseFirestore` can be used.
  static bool get ready => _ready;

  /// The reason Firebase is unavailable, or null when it is ready.
  static String? get error => _error;

  /// Initialises the default Firebase app. Safe to call more than once.
  static Future<bool> start() async {
    if (_ready) return true;
    try {
      if (Firebase.apps.isEmpty) {
        // Generated by `flutterfire configure --project=jewellery-suite--cloud`:
        // it carries the Android and Web apps registered in the project, so the
        // same options work on both platforms. On Android the values match
        // google-services.json.
        await Firebase.initializeApp(
          options: DefaultFirebaseOptions.currentPlatform,
        );
      }
      _ready = Firebase.apps.isNotEmpty;
      _error = _ready ? null : 'Firebase has no configured app for this build.';
    } catch (e) {
      _ready = false;
      _error = e.toString();
      debugPrint('Firebase unavailable (shop still works offline): $e');
    }
    return _ready;
  }
}
